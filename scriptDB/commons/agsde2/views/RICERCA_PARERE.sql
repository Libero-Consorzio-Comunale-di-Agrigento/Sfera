create or replace force view RICERCA_PARERE
(
   ID_DOCUMENTO,
   TIPO_DOCUMENTO,
   ID_DOCUMENTO_PRINCIPALE,
   TIPO_DOCUMENTO_PRINCIPALE,
   ENTE,
   OGGETTO,
   RISERVATO,
   CONTROLLO_FUNZIONARIO,
   STATO,
   ID_CATEGORIA,
   UO_PROPONENTE_PROGR,
   UO_PROPONENTE_DAL,
   UO_PROPONENTE_OTTICA,
   UO_PROPONENTE_DESCRIZIONE,
   UO_PROPONENTE_CODICE,
   UTENTE_SOGGETTO,
   TIPO_SOGGETTO,
   ID_COMPETENZA,
   COMP_UTENTE,
   COMP_UNITA_PROGR,
   COMP_UNITA_DAL,
   COMP_UNITA_OTTICA,
   COMP_RUOLO,
   COMP_LETTURA,
   COMP_MODIFICA,
   COMP_CANCELLAZIONE,
   ID_STEP,
   STEP_UTENTE,
   STEP_UNITA_PROGR,
   STEP_UNITA_DAL,
   STEP_UNITA_OTTICA,
   STEP_RUOLO,
   STEP_NOME,
   STEP_DESCRIZIONE,
   NUMERO_PASSAGGI,
   ULTIMO_ATTORE_FLUSSO,
   NUMERO_ATTO,
   ANNO_ATTO,
   REGISTRO_ATTO,
   DATA_ATTO,
   DATA_ADOZIONE,
   DATA_ESECUTIVITA,
   DATA_SCADENZA,
   NUMERO_ATTO_2,
   ANNO_ATTO_2,
   REGISTRO_ATTO_2,
   DATA_NUMERO_ATTO_2,
   NUMERO_PROPOSTA,
   ANNO_PROPOSTA,
   REGISTRO_PROPOSTA,
   DATA_PROPOSTA,
   NUMERO_PROTOCOLLO,
   ANNO_PROTOCOLLO,
   REGISTRO_PROTOCOLLO,
   CLASSIFICA_CODICE,
   CLASSIFICA_DAL,
   CLASSIFICA_DESCRIZIONE,
   FASCICOLO_ANNO,
   FASCICOLO_NUMERO,
   FASCICOLO_OGGETTO,
   ID_TIPOLOGIA,
   TITOLO_TIPOLOGIA,
   DESCRIZIONE_TIPOLOGIA,
   CODICE_ESTERNO_TIPOLOGIA,
   TIPO_PUBBLICAZIONE_ALBO,
   CON_IMPEGNO_SPESA,
   NUMERO_ALBO,
   ANNO_ALBO,
   DATA_PUBBLICAZIONE,
   DATA_FINE_PUBBLICAZIONE,
   LOG_CONSERVAZIONE,
   DATA_CONSERVAZIONE,
   STATO_CONSERVAZIONE,
   DA_INVIARE_CORTE_CONTI,
   DATA_INVIO_CORTE_CONTI,
   ID_TESTO,
   ID_FILE_ALLEGATO,
   ID_TIPO_ALLEGATO_VISTO,
   ESITO,
   UO_REDAZIONE_PROGR,
   UO_REDAZIONE_DAL,
   UO_REDAZIONE_OTTICA,
   UTENTE_FIRMATARIO,
   STATO_MARCATURA,
   STATO_FIRMA,
   DATA_ORDINAMENTO,
   ATTO_CONCLUSO,
   CUP,
   CIG,
   DATA_CONTROLLO_GESTIONE,
   ID_IMPATTO_GENERAZIONALE,
   CONTO_ECONOMICO,
   CODICE_PROGETTO,
   ID_TIPO_BUDGET,
   IMPORTO,
   IMPORTO_LIQUIDAZIONE,
   ELENCO_FIRMATARI,
   NOTE)
as
select vp.id_visto_parere as ID_DOCUMENTO,
       cast ('PARERE' as varchar (255)) as TIPO_DOCUMENTO,
       vp.id_proposta_delibera as ID_DOCUMENTO_PRINCIPALE,
      'PROPOSTA_DELIBERA' TIPO_DOCUMENTO_PRINCIPALE,
       vp.ente as ENTE,
       pd.oggetto as OGGETTO,
       pd.riservato as RISERVATO,
       pd.controllo_funzionario as CONTROLLO_FUNZIONARIO,
       upper (decode (vp.stato, 'ANNULLATO', vp.stato, nvl (sc.titolo, vp.stato))) as STATO,
       pd.id_categoria as ID_CATEGORIA,
       pds.unita_progr as UO_PROPONENTE_PROGR,
       pds.unita_dal as UO_PROPONENTE_DAL,
       pds.unita_ottica as UO_PROPONENTE_OTTICA,
       utility_pkg.get_uo_descrizione(pds.unita_progr, pds.unita_dal) as UO_PROPONENTE_DESCRIZIONE,
       null as UO_PROPONENTE_CODICE,
       pds.utente as UTENTE_SOGGETTO,
       pds.tipo_soggetto as TIPO_SOGGETTO,
       comp.id_visto_parere_competenza as ID_COMPETENZA,
       comp.utente as COMP_UTENTE,
       comp.unita_progr as COMP_UNITA_PROGR,
       comp.unita_dal as COMP_UNITA_DAL,
       comp.unita_ottica as COMP_UNITA_OTTICA,
       comp.ruolo as COMP_RUOLO,
       comp.lettura as COMP_LETTURA,
       comp.modifica as COMP_MODIFICA,
       comp.cancellazione as COMP_CANCELLAZIONE,
       s.id_engine_step as ID_STEP,
       sa.utente as STEP_UTENTE,
       sa.unita_progr as STEP_UNITA_PROGR,
       sa.unita_dal as STEP_UNITA_DAL,
       sa.unita_ottica as STEP_UNITA_OTTICA,
       sa.ruolo as STEP_RUOLO,
       sc.titolo as STEP_NOME,
       sc.descrizione as STEP_DESCRIZIONE,
       case when s.id_cfg_step is not null then
         (select count(*) from wkf_engine_step s2
           where s2.id_engine_iter = iter.id_engine_iter
             and s2.id_cfg_step = s.id_cfg_step
             and impostazioni_pkg.get_impostazione('EXCEL_NUMERO_PASSAGGI', pd.ente) = 'Y')
       end as NUMERO_PASSAGGI,
       decode(impostazioni_pkg.get_impostazione('EXCEL_ULTIMO_ATTORE_FLUSSO', pd.ente), 'Y', utility_pkg.get_nominativo_utente_ad4(iter.utente_upd, iter.ente), null) as ULTIMO_ATTORE_FLUSSO,
       cast (null as number) as  NUMERO_ATTO,
       cast (null as number) as  ANNO_ATTO,
       cast ('' as varchar2 (255)) as REGISTRO_ATTO,
       cast ('' as date) as DATA_ATTO,
       cast ('' as date) as DATA_ADOZIONE,
       cast ('' as date) as DATA_ESECUTIVITA,
       cast ('' as date) as DATA_SCADENZA,
       cast (null as number) as NUMERO_ATTO_2,
       cast (null as number) as ANNO_ATTO_2,
       cast ('' as varchar2 (255)) as REGISTRO_ATTO_2,
       cast (null as date) as DATA_NUMERO_ATTO_2,
       pd.numero_proposta as NUMERO_PROPOSTA,
       pd.anno_proposta as ANNO_PROPOSTA,
       pd.registro_proposta as REGISTRO_PROPOSTA,
       trunc (pd.data_proposta) as DATA_PROPOSTA,
       cast (null as number) as NUMERO_PROTOCOLLO,
       cast (null as number) as ANNO_PROTOCOLLO,
       cast ('' as varchar2 (255)) as REGISTRO_PROTOCOLLO,
       pd.classifica_codice as CLASSIFICA_CODICE,
       pd.classifica_dal as CLASSIFICA_DAL,
       pd.classifica_descrizione as CLASSIFICA_DESCRIZIONE,
       pd.fascicolo_anno as FASCICOLO_ANNO,
       pd.fascicolo_numero as FASCICOLO_NUMERO,
       pd.fascicolo_oggetto as FASCICOLO_OGGETTO,
       vp.id_tipologia as ID_TIPOLOGIA,
       tipo.titolo as TITOLO_TIPOLOGIA,
       tipo.descrizione as DESCRIZIONE_TIPOLOGIA,
       null as CODICE_ESTERNO_TIPOLOGIA,
       null as TIPO_PUBBLICAZIONE_ALBO,
       tipo.contabile as CON_IMPEGNO_SPESA,
       cast (null as number) as NUMERO_ALBO,
       cast (null as number) as ANNO_ALBO,
       cast (null as date) as DATA_PUBBLICAZIONE,
       cast (null as date) as DATA_FINE_PUBBLICAZIONE,
       jcons_pkg.get_log_conservazione (pd.id_documento_esterno) as LOG_CONSERVAZIONE,
       jcons_pkg.get_data_conservazione (pd.id_documento_esterno) as DATA_CONSERVAZIONE,
       cast ('' as varchar2 (255)) as STATO_CONSERVAZIONE,
       cast (pd.da_inviare_corte_conti as char (1)) as DA_INVIARE_CORTE_CONTI,
       cast (null as date) as DATA_INVIO_CORTE_CONTI,
       vp.id_file_allegato_testo as ID_TESTO,
       af.id_file as ID_FILE_ALLEGATO,
       alle.id_tipo_allegato as ID_TIPO_ALLEGATO_VISTO,
       vp.esito as ESITO,
       vp.unita_progr as UO_REDAZIONE_PROGR,
       vp.unita_dal as UO_REDAZIONE_DAL,
       vp.unita_ottica as UO_REDAZIONE_OTTICA,
       vp.utente_firmatario as UTENTE_FIRMATARIO,
       vp.stato_marcatura as STATO_MARCATURA,
       vp.stato_firma as STATO_FIRMA,
       vp.data_ordinamento as DATA_ORDINAMENTO,
       cast ('N' as char (1)) as ATTO_CONCLUSO,
       null as CUP,
       null as CIG,
       cast (null as date) as DATA_CONTROLLO_GESTIONE,
       cast(null as number) as ID_IMPATTO_GENERAZIONALE,
       null as CONTO_ECONOMICO,
       null as CODICE_PROGETTO,
       cast (null as number) as ID_TIPO_BUDGET,
       cast (null as number) as IMPORTO,
       cast (null as number) as IMPORTO_LIQUIDAZIONE,
       utility_pkg.get_elenco_firmatari_documento (vp.id_visto_parere, vp.ente, 'VISTO_PARERE'),
       null as NOTE
  from wkf_engine_iter iter,
       wkf_engine_step s,
       wkf_engine_step_attori sa,
       wkf_cfg_step sc,
       proposte_delibera_soggetti pds,
       proposte_delibera pd,
       allegati alle,
       visti_pareri vp,
       visti_pareri_competenze comp,
       tipi_visto_parere tipo,
       allegati_file af
 where sc.id_cfg_step(+) = s.id_cfg_step
   and sa.id_engine_step(+) = s.id_engine_step
   and s.id_engine_step(+) = iter.id_step_corrente
   and iter.id_engine_iter(+) = vp.id_engine_iter
   and alle.id_visto_parere(+) = vp.id_visto_parere
   and comp.id_visto_parere = vp.id_visto_parere
   and vp.id_tipologia = tipo.id_tipo_visto_parere
   and pds.id_proposta_delibera = pd.id_proposta_delibera
   and pds.tipo_soggetto = 'UO_PROPONENTE'
   and pd.valido = 'Y'
   and vp.id_proposta_delibera = pd.id_proposta_delibera
   and af.id_allegato(+) = alle.id_allegato
   and vp.valido = 'Y'
union all
select vp.id_visto_parere as ID_DOCUMENTO,
       cast ('PARERE' as varchar (255)) as TIPO_DOCUMENTO,
       nvl(vp.id_delibera, vp.id_proposta_delibera) as ID_DOCUMENTO_PRINCIPALE,
       cast ('DELIBERA' as varchar (255)) as TIPO_DOCUMENTO_PRINCIPALE,
       vp.ente as ENTE,
       pd.oggetto as OGGETTO,
       pd.riservato as RISERVATO,
       pd.controllo_funzionario as CONTROLLO_FUNZIONARIO,
       upper (decode (vp.stato, 'ANNULLATO', vp.stato, nvl (sc.titolo, vp.stato))) as STATO,
       pd.id_categoria as ID_CATEGORIA,
       pds.unita_progr as UO_PROPONENTE_PROGR,
       pds.unita_dal as UO_PROPONENTE_DAL,
       pds.unita_ottica as UO_PROPONENTE_OTTICA,
       utility_pkg.get_uo_descrizione(pds.unita_progr, pds.unita_dal) as UO_PROPONENTE_DESCRIZIONE,
       null as UO_PROPONENTE_CODICE,
       pds.utente as UTENTE_SOGGETTO,
       pds.tipo_soggetto as TIPO_SOGGETTO,
       comp.id_visto_parere_competenza as ID_COMPETENZA,
       comp.utente as COMP_UTENTE,
       comp.unita_progr as COMP_UNITA_PROGR,
       comp.unita_dal as COMP_UNITA_DAL,
       comp.unita_ottica as COMP_UNITA_OTTICA,
       comp.ruolo as COMP_RUOLO,
       comp.lettura as COMP_LETTURA,
       comp.modifica as COMP_MODIFICA,
       comp.cancellazione as COMP_CANCELLAZIONE,
       s.id_engine_step as ID_STEP,
       sa.utente as STEP_UTENTE,
       sa.unita_progr as STEP_UNITA_PROGR,
       sa.unita_dal as STEP_UNITA_DAL,
       sa.unita_ottica as STEP_UNITA_OTTICA,
       sa.ruolo as STEP_RUOLO,
       sc.titolo as STEP_NOME,
       sc.descrizione as STEP_DESCRIZIONE,
       case when s.id_cfg_step is not null then
         (select count(*) from wkf_engine_step s2
           where s2.id_engine_iter = iter.id_engine_iter
             and s2.id_cfg_step = s.id_cfg_step
             and impostazioni_pkg.get_impostazione('EXCEL_NUMERO_PASSAGGI', deli.ente) = 'Y')
       end as NUMERO_PASSAGGI,
       decode(impostazioni_pkg.get_impostazione('EXCEL_ULTIMO_ATTORE_FLUSSO', deli.ente), 'Y', utility_pkg.get_nominativo_utente_ad4(iter.utente_upd, iter.ente), null) as ULTIMO_ATTORE_FLUSSO,
       deli.numero_delibera as NUMERO_ATTO,
       deli.anno_delibera as ANNO_ATTO,
       deli.registro_delibera as REGISTRO_ATTO,
       trunc (deli.data_numero_delibera) as DATA_ATTO,
       trunc (deli.data_adozione) as DATA_ADOZIONE,
       trunc (deli.data_esecutivita) as DATA_ESECUTIVITA,
       cast ('' as date) as DATA_SCADENZA,
       cast (null as number) as NUMERO_ATTO_2,
       cast (null as number) as ANNO_ATTO_2,
       cast ('' as varchar2 (255)) as REGISTRO_ATTO_2,
       cast (null as date) as DATA_NUMERO_ATTO_2,
       pd.numero_proposta as NUMERO_PROPOSTA,
       pd.anno_proposta as ANNO_PROPOSTA,
       pd.registro_proposta as REGISTRO_PROPOSTA,
       trunc (pd.data_proposta) as DATA_PROPOSTA,
       deli.numero_protocollo as NUMERO_PROTOCOLLO,
       deli.anno_protocollo as ANNO_PROTOCOLLO,
       deli.registro_protocollo as REGISTRO_PROTOCOLLO,
       deli.classifica_codice as CLASSIFICA_CODICE,
       deli.classifica_dal as CLASSIFICA_DAL,
       deli.classifica_descrizione as CLASSIFICA_DESCRIZIONE,
       deli.fascicolo_anno as FASCICOLO_ANNO,
       deli.fascicolo_numero as FASCICOLO_NUMERO,
       deli.fascicolo_oggetto as FASCICOLO_OGGETTO,
       vp.id_tipologia as ID_TIPOLOGIA,
       tipo.titolo as TITOLO_TIPOLOGIA,
       tipo.descrizione as DESCRIZIONE_TIPOLOGIA,
       null as CODICE_ESTERNO_TIPOLOGIA,
       null as TIPO_PUBBLICAZIONE_ALBO,
       tipo.contabile as CON_IMPEGNO_SPESA,
       deli.numero_albo as NUMERO_ALBO,
       deli.anno_albo as ANNO_ALBO,
       trunc (deli.data_pubblicazione) as DATA_PUBBLICAZIONE,
       trunc (deli.data_fine_pubblicazione) as DATA_FINE_PUBBLICAZIONE,
       jcons_pkg.get_log_conservazione (pd.id_documento_esterno) as LOG_CONSERVAZIONE,
       jcons_pkg.get_data_conservazione (pd.id_documento_esterno) as DATA_CONSERVAZIONE,
       deli.stato_conservazione as STATO_CONSERVAZIONE,
       cast (nvl (deli.da_inviare_corte_conti, pd.da_inviare_corte_conti) as char (1)) as DA_INVIARE_CORTE_CONTI,
       trunc (deli.data_invio_corte_conti) as DATA_INVIO_CORTE_CONTI,
       vp.id_file_allegato_testo as ID_TESTO,
       af.id_file as ID_FILE_ALLEGATO,
       alle.id_tipo_allegato as ID_TIPO_ALLEGATO_VISTO,
       vp.esito as ESITO,
       vp.unita_progr as UO_REDAZIONE_PROGR,
       vp.unita_dal as UO_REDAZIONE_DAL,
       vp.unita_ottica as UO_REDAZIONE_OTTICA,
       vp.utente_firmatario as UTENTE_FIRMATARIO,
       vp.stato_marcatura as STATO_MARCATURA,
       vp.stato_firma as STATO_FIRMA,
       vp.data_ordinamento as DATA_ORDINAMENTO,
       cast ('N' as char (1)) as ATTO_CONCLUSO,
       null as CUP,
       null as CIG,
       cast (null as date) as DATA_CONTROLLO_GESTIONE,
       cast(null as number) as ID_IMPATTO_GENERAZIONALE,
       null as CONTO_ECONOMICO,
       null as CODICE_PROGETTO,
       cast (null as number) as ID_TIPO_BUDGET,
       cast (null as number) as IMPORTO,
       cast (null as number) as IMPORTO_LIQUIDAZIONE,
       utility_pkg.get_elenco_firmatari_documento (vp.id_visto_parere, vp.ente, 'VISTO_PARERE'),
       null as NOTE
  from wkf_engine_iter iter,
       wkf_engine_step s,
       wkf_engine_step_attori sa,
       wkf_cfg_step sc,
       delibere deli,
       proposte_delibera_soggetti pds,
       proposte_delibera pd,
       allegati alle,
       visti_pareri vp,
       visti_pareri_competenze comp,
       tipi_visto_parere tipo,
       allegati_file af
 where sc.id_cfg_step(+) = s.id_cfg_step
   and sa.id_engine_step(+) = s.id_engine_step
   and s.id_engine_step(+) = iter.id_step_corrente
  and iter.id_engine_iter(+) = vp.id_engine_iter
   and alle.id_visto_parere(+) = vp.id_visto_parere
   and comp.id_visto_parere = vp.id_visto_parere
   and vp.id_tipologia = tipo.id_tipo_visto_parere
   and pds.id_proposta_delibera = pd.id_proposta_delibera
   and pds.tipo_soggetto = 'UO_PROPONENTE'
   and pd.valido = 'Y'
   and deli.valido = 'Y'
   and deli.id_proposta_delibera = pd.id_proposta_delibera
   and vp.id_delibera = deli.id_delibera
   and af.id_allegato(+) = alle.id_allegato
   and vp.valido = 'Y'
