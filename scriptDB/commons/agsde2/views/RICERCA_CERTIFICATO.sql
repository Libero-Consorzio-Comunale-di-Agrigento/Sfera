create or replace force view RICERCA_CERTIFICATO
(
   ID_DOCUMENTO,
   TIPO_DOCUMENTO,
   ID_DOCUMENTO_PRINCIPALE,
   TIPO_DOCUMENTO_PRINCIPALE,
   ENTE,
   OGGETTO,
   RISERVATO,
   CONTROLLO_FUNZIONARIO,
   STATO,
   ID_CATEGORIA,
   UO_PROPONENTE_PROGR,
   UO_PROPONENTE_DAL,
   UO_PROPONENTE_OTTICA,
   UO_PROPONENTE_DESCRIZIONE,
   UO_PROPONENTE_CODICE,
   UTENTE_SOGGETTO,
   TIPO_SOGGETTO,
   ID_COMPETENZA,
   COMP_UTENTE,
   COMP_UNITA_PROGR,
   COMP_UNITA_DAL,
   COMP_UNITA_OTTICA,
   COMP_RUOLO,
   COMP_LETTURA,
   COMP_MODIFICA,
   COMP_CANCELLAZIONE,
   ID_STEP,
   STEP_UTENTE,
   STEP_UNITA_PROGR,
   STEP_UNITA_DAL,
   STEP_UNITA_OTTICA,
   STEP_RUOLO,
   STEP_NOME,
   STEP_DESCRIZIONE,
   NUMERO_PASSAGGI,
   ULTIMO_ATTORE_FLUSSO,
   NUMERO_ATTO,
   ANNO_ATTO,
   REGISTRO_ATTO,
   DATA_ATTO,
   DATA_ADOZIONE,
   DATA_ESECUTIVITA,
   DATA_SCADENZA,
   NUMERO_ATTO_2,
   ANNO_ATTO_2,
   REGISTRO_ATTO_2,
   DATA_NUMERO_ATTO_2,
   NUMERO_PROPOSTA,
   ANNO_PROPOSTA,
   REGISTRO_PROPOSTA,
   DATA_PROPOSTA,
   NUMERO_PROTOCOLLO,
   ANNO_PROTOCOLLO,
   REGISTRO_PROTOCOLLO,
   CLASSIFICA_CODICE,
   CLASSIFICA_DAL,
   CLASSIFICA_DESCRIZIONE,
   FASCICOLO_ANNO,
   FASCICOLO_NUMERO,
   FASCICOLO_OGGETTO,
   ID_TIPOLOGIA,
   TITOLO_TIPOLOGIA,
   DESCRIZIONE_TIPOLOGIA,
   CODICE_ESTERNO_TIPOLOGIA,
   TIPO_PUBBLICAZIONE_ALBO,
   CON_IMPEGNO_SPESA,
   NUMERO_ALBO,
   ANNO_ALBO,
   DATA_PUBBLICAZIONE,
   DATA_FINE_PUBBLICAZIONE,
   LOG_CONSERVAZIONE,
   DATA_CONSERVAZIONE,
   STATO_CONSERVAZIONE,
   DA_INVIARE_CORTE_CONTI,
   DATA_INVIO_CORTE_CONTI,
   ID_TESTO,
   ID_FILE_ALLEGATO,
   TIPO,
   UTENTE_FIRMATARIO,
   STATO_MARCATURA,
   STATO_FIRMA,
   DATA_ORDINAMENTO,
   ATTO_CONCLUSO,
   CUP,
   CIG,
   DATA_CONTROLLO_GESTIONE,
   ID_IMPATTO_GENERAZIONALE,
   CONTO_ECONOMICO,
   CODICE_PROGETTO,
   ID_TIPO_BUDGET,
   IMPORTO,
   IMPORTO_LIQUIDAZIONE,
   ELENCO_FIRMATARI,
   NOTE
)
as
select vp.id_certificato as ID_DOCUMENTO,
       cast ('CERTIFICATO' as varchar (255)) as TIPO_DOCUMENTO,
       vp.id_determina as ID_DOCUMENTO_PRINCIPALE,
       cast ('DETERMINA' as varchar (255)) as TIPO_DOCUMENTO_PRINCIPALE,
       vp.ente as ENTE,
       dete.oggetto as OGGETTO,
       dete.riservato as RISERVATO,
       dete.controllo_funzionario as CONTROLLO_FUNZIONARIO,
       upper (decode (vp.stato, 'ANNULLATO', vp.stato, nvl (sc.titolo, vp.stato))) as STATO,
       dete.id_categoria as ID_CATEGORIA,
       pds.unita_progr as UO_PROPONENTE_PROGR,
       pds.unita_dal as UO_PROPONENTE_DAL,
       pds.unita_ottica as UO_PROPONENTE_OTTICA,
       so4_util.anuo_get_descrizione (pds.unita_progr, pds.unita_dal) as UO_PROPONENTE_DESCRIZIONE,
       null as UO_PROPONENTE_CODICE,
       pds.utente as UTENTE_SOGGETTO,
       pds.tipo_soggetto as TIPO_SOGGETTO,
       comp.id_certificato_competenza as ID_COMPETENZA,
       comp.utente as COMP_UTENTE,
       comp.unita_progr as COMP_UNITA_PROGR,
       comp.unita_dal as COMP_UNITA_DAL,
       comp.unita_ottica as COMP_UNITA_OTTICA,
       comp.ruolo as COMP_RUOLO,
       comp.lettura as COMP_LETTURA,
       comp.modifica as COMP_MODIFICA,
       comp.cancellazione as COMP_CANCELLAZIONE,
       s.id_engine_step as ID_STEP,
       sa.utente as STEP_UTENTE,
       sa.unita_progr as STEP_UNITA_PROGR,
       sa.unita_dal as STEP_UNITA_DAL,
       sa.unita_ottica as STEP_UNITA_OTTICA,
       sa.ruolo as STEP_RUOLO,
       sc.titolo as STEP_NOME,
       sc.descrizione as STEP_DESCRIZIONE,
       case when s.id_cfg_step is not null then
         (select count(*) from wkf_engine_step s2
           where s2.id_engine_iter = iter.id_engine_iter
             and s2.id_cfg_step = s.id_cfg_step
             and impostazioni_pkg.get_impostazione('EXCEL_NUMERO_PASSAGGI', dete.ente) = 'Y')
       end as NUMERO_PASSAGGI,
       decode(impostazioni_pkg.get_impostazione('EXCEL_ULTIMO_ATTORE_FLUSSO', dete.ente), 'Y', utility_pkg.get_nominativo_soggetto(iter.utente_upd, iter.ente), null) as ULTIMO_ATTORE_FLUSSO,
       dete.numero_determina as NUMERO_ATTO,
       dete.anno_determina as ANNO_ATTO,
       dete.registro_determina as REGISTRO_ATTO,
       trunc (dete.data_numero_determina) as DATA_ATTO,
       trunc (dete.data_numero_determina) as DATA_ADOZIONE,
       trunc (dete.data_esecutivita) as DATA_ESECUTIVITA,
       trunc (dete.data_scadenza) as DATA_SCADENZA,
       dete.numero_determina_2 as NUMERO_ATTO_2,
       dete.anno_determina_2 as ANNO_ATTO_2,
       dete.registro_determina_2 as REGISTRO_ATTO_2,
       dete.data_numero_determina_2 as DATA_NUMERO_ATTO_2,
       dete.numero_proposta as NUMERO_PROPOSTA,
       dete.anno_proposta as ANNO_PROPOSTA,
       dete.registro_proposta as REGISTRO_PROPOSTA,
       trunc (dete.data_proposta) as DATA_PROPOSTA,
       dete.numero_protocollo as NUMERO_PROTOCOLLO,
       dete.anno_protocollo as ANNO_PROTOCOLLO,
       dete.registro_protocollo as REGISTRO_PROTOCOLLO,
       dete.classifica_codice as CLASSIFICA_CODICE,
       dete.classifica_dal as CLASSIFICA_DAL,
       dete.classifica_descrizione as CLASSIFICA_DESCRIZIONE,
       dete.fascicolo_anno as FASCICOLO_ANNO,
       dete.fascicolo_numero as FASCICOLO_NUMERO,
       dete.fascicolo_oggetto as FASCICOLO_OGGETTO,
       vp.id_tipologia as ID_TIPOLOGIA,
       tipo.titolo as TITOLO_TIPOLOGIA,
       tipo.descrizione as DESCRIZIONE_TIPOLOGIA,
       null as CODICE_ESTERNO_TIPOLOGIA,
       null as TIPO_PUBBLICAZIONE_ALBO,
       cast ('' as char (1)) as CON_IMPEGNO_SPESA,
       dete.numero_albo as NUMERO_ALBO,
       dete.anno_albo as ANNO_ALBO,
       trunc (dete.data_pubblicazione) as DATA_PUBBLICAZIONE,
       trunc (dete.data_fine_pubblicazione) as DATA_FINE_PUBBLICAZIONE,
       jcons_pkg.get_log_conservazione (dete.id_documento_esterno) as LOG_CONSERVAZIONE,
       jcons_pkg.get_data_conservazione (dete.id_documento_esterno) as DATA_CONSERVAZIONE,
       dete.stato_conservazione as STATO_CONSERVAZIONE,
       dete.da_inviare_corte_conti as DA_INVIARE_CORTE_CONTI,
       trunc (dete.data_invio_corte_conti) as DATA_INVIO_CORTE_CONTI,
       vp.id_file_allegato_testo as ID_TESTO,
       vp.id_file_allegato_testo as ID_FILE_ALLEGATO,
       vp.tipo as TIPO,
       vp.firmatario as UTENTE_FIRMATARIO,
       vp.stato_marcatura as STATO_MARCATURA,
       vp.stato_firma as STATO_FIRMA,
       null as DATA_ORDINAMENTO,
       cast ('N' as char (1)) as ATTO_CONCLUSO,
       null as CUP,
       null as CIG,
       cast (null as date) as DATA_CONTROLLO_GESTIONE,
       cast (null as number) as ID_IMPATTO_GENERAZIONALE,
       null as CONTO_ECONOMICO,
       null as CODICE_PROGETTO,
       null as ID_TIPO_BUDGET,
       null as IMPORTO,
       cast (null as number) as IMPORTO_LIQUIDAZIONE,
       utility_pkg.get_elenco_firmatari_documento (vp.id_certificato, vp.ente, 'CERTIFICATO'),
       null as NOTE
  from wkf_engine_iter iter,
       wkf_engine_step s,
       wkf_engine_step_attori sa,
       wkf_cfg_step sc,
       determine_soggetti pds,
       determine dete,
       certificati vp,
       certificati_competenze comp,
       tipi_certificato tipo
 where sc.id_cfg_step(+) = s.id_cfg_step
   and sa.id_engine_step(+) = s.id_engine_step
   and s.id_engine_step(+) = iter.id_step_corrente
   and iter.id_engine_iter(+) = vp.id_engine_iter
   and comp.id_certificato = vp.id_certificato
   and vp.id_tipologia = tipo.id_tipo_certificato
   and pds.id_determina = dete.id_determina
   and pds.tipo_soggetto = 'UO_PROPONENTE'
   and dete.valido = 'Y'
   and vp.id_determina = dete.id_determina
   and vp.valido = 'Y'
union all
select vp.id_certificato as ID_DOCUMENTO,
       cast ('CERTIFICATO' as varchar (255)) as TIPO_DOCUMENTO,
       vp.id_delibera as ID_DOCUMENTO_PRINCIPALE,
       cast ('DELIBERA' as varchar (255)) as TIPO_DOCUMENTO_PRINCIPALE,
       vp.ente as ENTE,
       dete.oggetto as OGGETTO,
       dete.riservato as RISERVATO,
       dete.controllo_funzionario as CONTROLLO_FUNZIONARIO,
       upper (decode (vp.stato, 'ANNULLATO', vp.stato, nvl (sc.titolo, vp.stato))) as STATO,
       dete.id_categoria as ID_CATEGORIA,
       pds.unita_progr as UO_PROPONENTE_PROGR,
       pds.unita_dal as UO_PROPONENTE_DAL,
       pds.unita_ottica as UO_PROPONENTE_OTTICA,
       so4_util.anuo_get_descrizione (pds.unita_progr, pds.unita_dal) as UO_PROPONENTE_DESCRIZIONE,
       null as UO_PROPONENTE_CODICE,
       pds.utente as UTENTE_SOGGETTO,
       pds.tipo_soggetto as TIPO_SOGGETTO,
       comp.id_certificato_competenza as ID_COMPETENZA,
       comp.utente as COMP_UTENTE,
       comp.unita_progr as COMP_UNITA_PROGR,
       comp.unita_dal as COMP_UNITA_DAL,
       comp.unita_ottica as COMP_UNITA_OTTICA,
       comp.ruolo as COMP_RUOLO,
       comp.lettura as COMP_LETTURA,
       comp.modifica as COMP_MODIFICA,
       comp.cancellazione as COMP_CANCELLAZIONE,
       s.id_engine_step as ID_STEP,
       sa.utente as STEP_UTENTE,
       sa.unita_progr as STEP_UNITA_PROGR,
       sa.unita_dal as STEP_UNITA_DAL,
       sa.unita_ottica as STEP_UNITA_OTTICA,
       sa.ruolo as STEP_RUOLO,
       sc.titolo as STEP_NOME,
       sc.descrizione as STEP_DESCRIZIONE,
       case when s.id_cfg_step is not null then
         (select count(*) from wkf_engine_step s2
           where s2.id_engine_iter = iter.id_engine_iter
             and s2.id_cfg_step = s.id_cfg_step
             and impostazioni_pkg.get_impostazione('EXCEL_NUMERO_PASSAGGI', deli.ente) = 'Y')
       end as NUMERO_PASSAGGI,
       decode(impostazioni_pkg.get_impostazione('EXCEL_ULTIMO_ATTORE_FLUSSO', deli.ente), 'Y', utility_pkg.get_nominativo_utente_ad4(iter.utente_upd, iter.ente), null) as ULTIMO_ATTORE_FLUSSO,
       deli.numero_delibera as NUMERO_ATTO,
       deli.anno_delibera as ANNO_ATTO,
       deli.registro_delibera as REGISTRO_ATTO,
       trunc (deli.data_numero_delibera) as DATA_ATTO,
       trunc (deli.data_adozione) as DATA_ADOZIONE,
       trunc (deli.data_esecutivita) as DATA_ESECUTIVITA,
       cast ('' as date) as DATA_SCADENZA,
       cast (null as number) as NUMERO_ATTO_2,
       cast (null as number) as ANNO_ATTO_2,
       cast ('' as varchar2 (255)) as REGISTRO_ATTO_2,
       cast (null as date) as NUMERO_ATTO_2,
       dete.numero_proposta as NUMERO_PROPOSTA,
       dete.anno_proposta as ANNO_PROPOSTA,
       dete.registro_proposta as REGISTRO_PROPOSTA,
       trunc (dete.data_proposta) as DATA_PROPOSTA,
       deli.numero_protocollo as NUMERO_PROTOCOLLO,
       deli.anno_protocollo as ANNO_PROTOCOLLO,
       deli.registro_protocollo as REGISTRO_PROTOCOLLO,
       deli.classifica_codice as CLASSIFICA_CODICE,
       deli.classifica_dal as CLASSIFICA_DAL,
       deli.classifica_descrizione as CLASSIFICA_DESCRIZIONE,
       deli.fascicolo_anno as FASCICOLO_ANNO,
       deli.fascicolo_numero as FASCICOLO_NUMERO,
       deli.fascicolo_oggetto as FASCICOLO_OGGETTO,
       vp.id_tipologia as ID_TIPOLOGIA,
       tipo.titolo as TITOLO_TIPOLOGIA,
       tipo.descrizione as DESCRIZIONE_TIPOLOGIA,
       null as CODICE_ESTERNO_TIPOLOGIA,
       null as TIPO_PUBBLICAZIONE_ALBO,
       cast ('' as char (1)) as CON_IMPEGNO_SPESA,
       deli.numero_albo as NUMERO_ALBO,
       deli.anno_albo as ANNO_ALBO,
       trunc (deli.data_pubblicazione) as DATA_PUBBLICAZIONE,
       trunc (deli.data_fine_pubblicazione) as DATA_FINE_PUBBLICAZIONE,
       jcons_pkg.get_log_conservazione (deli.id_documento_esterno) as LOG_CONSERVAZIONE,
       jcons_pkg.get_data_conservazione (deli.id_documento_esterno) as DATA_CONSERVAZIONE,
       deli.stato_conservazione as STATO_CONSERVAZIONE,
       deli.da_inviare_corte_conti as DA_INVIARE_CORTE_CONTI,
       trunc (deli.data_invio_corte_conti) as DATA_INVIO_CORTE_CONTI,
       vp.id_file_allegato_testo as ID_TESTO,
       null as ID_FILE_ALLEGATO,
       vp.tipo as TIPO,
       vp.firmatario as UTENTE_FIRMATARIO,
       vp.stato_marcatura as STATO_MARCATURA,
       vp.stato_firma as STATO_FIRMA,
       null as DATA_ORDINAMENTO,
       cast ('N' as char (1)) as ATTO_CONCLUSO,
       null as CUP,
       null as CIG,
       cast (null as date) as DATA_CONTROLLO_GESTIONE,
       cast (null as number) as ID_IMPATTO_GENERAZIONALE,
       null as CONTO_ECONOMICO,
       null as CODICE_PROGETTO,
       cast (null as number) as ID_TIPO_BUDGET,
       cast (null as number) as IMPORTO,
       cast (null as number) as IMPORTO_LIQUIDAZIONE,
       utility_pkg.get_elenco_firmatari_documento (vp.id_certificato, vp.ente, 'CERTIFICATO'),
       null as NOTE
  from wkf_engine_iter iter,
       wkf_engine_step s,
       wkf_engine_step_attori sa,
       wkf_cfg_step sc,
       proposte_delibera_soggetti pds,
       proposte_delibera dete,
       delibere deli,
       certificati vp,
       certificati_competenze comp,
       tipi_certificato tipo
 where sc.id_cfg_step(+) = s.id_cfg_step
   and sa.id_engine_step(+) = s.id_engine_step
   and s.id_engine_step(+) = iter.id_step_corrente
   and iter.id_engine_iter(+) = vp.id_engine_iter
   and comp.id_certificato = vp.id_certificato
   and vp.id_tipologia = tipo.id_tipo_certificato
   and pds.id_proposta_delibera = dete.id_proposta_delibera
   and pds.tipo_soggetto = 'UO_PROPONENTE'
   and deli.valido = 'Y'
   and dete.id_proposta_delibera = deli.id_proposta_delibera
   and vp.id_delibera = deli.id_delibera
   and vp.valido = 'Y'
